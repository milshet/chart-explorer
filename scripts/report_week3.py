#!/usr/bin/env python3
"""Week 3 results draft (task 3.9), generated from committed artefacts: no figure in it is typed by hand.

  python scripts/report_week3.py            # print
  python scripts/report_week3.py --write    # write docs/report_draft_week3.md

Every section renders a number read from results/ or data/, or the string NOT MEASURED. An omitted row would read
as "no issue here"; NOT MEASURED says nobody checked. The closing list of gaps is assembled from those strings.
"""
import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "scripts"))
import threeway  # noqa: E402
from rag import retrieve as R  # noqa: E402

NM = "NOT MEASURED"


def read(path):
    p = REPO / path
    return json.loads(p.read_text(encoding="utf-8")) if p.is_file() else None


def pct(v):
    return NM if v is None else f"{100 * v:.1f}%"


def build():
    gaps, out = [], ["# Week 3 results — generated draft", "",
                     "_Generated by `scripts/report_week3.py` from committed files; regenerate, do not edit._", ""]

    s = read("data/v2.0/tables/table_index.json")["stats"]
    out += ["## Table corpus (3.0d)", "",
            f"{s['tables']} tables / {s['rows']} rows: {s['from_records']} from frozen records, {s['distractor_only']} "
            f"distractor-only; {s['catalogue_records_compared']} record-level comparisons with the selection catalogue, "
            f"{s['catalogue_disagreements']} disagreements. {s['records_undefined_gold']} unanswerable records have no "
            f"gold table by construction. Corpus sha256 `{s['corpus_sha256'][:12]}…`.", ""]

    c = read("data/eval_c/stats.json")
    out += ["## Eval-C (3.0c)", "", f"{c['n']} probes, " + ", ".join(f"{k} {v}" for k, v in c["by_reason"].items())
            + f"; {c['by_origin'].get('template', 0)} templated, {c['by_origin'].get('catalogue', 0)} real unused questions; "
              f"{c['distinct_charts']} distinct held-out charts.", ""]

    out += ["## Abstention pair (3.0b), test", "", "| Evaluation | True abstention | False abstention |", "|---|---|---|"]
    for f in sorted((REPO / "results/evals").glob("*_test_*/summary.json")):
        a = json.loads(f.read_text(encoding="utf-8"))["overall"]["abstention"]
        out.append(f"| {f.parent.name} | {round(a['true_abstention'] * a['n_unanswerable'])}/{a['n_unanswerable']} | "
                   f"{round(a['false_abstention'] * a['n_answerable'])}/{a['n_answerable']} |")
    evc = sorted((REPO / "results/evals").glob("*_eval_c_*/summary.json"))
    if not evc:
        gaps.append("Eval-C has not been scored for any model")
        out += ["", f"Eval-C true abstention: {NM}."]
    out.append("")

    t = read("results/evals/run_a_r16-adapter_test_image_only_cot_0shot_bf16/taxonomy.json")
    errs = t["n"] - t["categories"]["ok"]
    out += ["## Error taxonomy (3.0e), Run A on test", "",
            f"{errs} errors of {t['n']} ({pct(t['error_rate'])}; 1 − error rate = relaxed accuracy {pct(t['relaxed_accuracy'])}):",
            ", ".join(f"{k} {v}" for k, v in t["categories"].items() if k != "ok" and v) + ".",
            f"Flags: {', '.join(f'{k} {v}' for k, v in t['flags'].items()) or 'none'}.", ""]

    r = read("results/rag/retrieval.json")
    ch = r["chosen"]
    out += ["## Retrieval (3.1–3.4)", "",
            f"Chosen on {r['selection']['n']} train rows ({r['chosen_basis']}): {ch['chunking']} chunks, {ch['retriever']}.",
            "Embedding retriever against the lexical floor: "
            + ("measured." if any(x["retriever"].startswith("embed") for x in r["selection"]["results"]) else NM) , "",
            "| Split / query plan | recall@1 | recall@3 | recall@5 | MRR | n scorable | n unscorable |", "|---|---|---|---|---|---|---|"]
    if not any(x["retriever"].startswith("embed") for x in r["selection"]["results"]):
        gaps.append("no embedding model compared against the lexical floor (task 3.3)")
    for k, m in r["headline"].items():
        out.append(f"| {k} | {m['recall@1']} | {m['recall@3']} | {m['recall@5']} | {m['mrr']} | {m['n_scorable']} | {m['n_unscorable']} |")
    measured = {x["retriever"] for x in r["selection"]["results"]}
    missing = [f"embed:{n}" for n in R.EMBED_MODELS if f"embed:{n}" not in measured] + \
              [f"bm25>rerank:{n}" for n in R.RERANKERS if f"bm25>rerank:{n}" not in measured]
    out += ["", "Every chunking, query-plan, embedding and reranking decision, with its rule and outcome: "
            "`docs/RAG.md`. Not yet measured: " + (", ".join(f"`{m}`" for m in missing) if missing else "none") + ".", ""]
    if missing:
        gaps.append(f"{len(missing)} embedding/reranking candidates not measured (tasks 3.10, 3.11)")

    cmp, deg = threeway.comparison(), threeway.degradation()
    out += ["## Required comparison (3.5) and retrieval failure (3.6)", "", threeway.markdown(cmp, deg), ""]
    gaps += [f"{n} (3.5)" for n, v in cmp["conditions"].items() if v == NM]
    gaps += [f"retrieval-failure verdict for {n} (3.6)" for n, v in deg.items() if v == NM]

    out += ["## LLM-as-judge (3.7, 3.13)", ""]
    j = sorted((REPO / "results/judge").glob("*/summary.json"))
    if not j:
        out += [f"Judge verdicts: {NM}.", ""]
        gaps.append("LLM-as-judge rubric not run (3.7, 3.13)")
    for p in j:
        s = json.loads(p.read_text(encoding="utf-8"))
        out += [f"**{p.parent.name}**, judged by `{s.get('judge_model', 'unrecorded')}` ({s.get('backend', 'anthropic')}): "
                f"{s['n']} rows, {s['n_excluded']} excluded as unreadable (not scored zero).", "",
                "| Axis | yes / graded |", "|---|---|"]
        out += [f"| {a} | {s[a]['yes']}/{s[a]['n']} |" for a in ("correctness", "grounding", "abstention")]
        out += ["", f"Judge vs the scorer's `evidence_grounded`: {len(s['grounding_disagreements'])} disagreements.", ""]
        x = s.get("abstention_vs_exact")
        if x:
            out += [f"**The judge checked against an exact answer:** declining is right if and only if the gold is null, "
                    f"so its abstention verdict can be scored without a human. It agrees on {x['agree']}/{x['n']}. "
                    "By case: " + "; ".join(f"{k} {v}" for k, v in x["by_case"].items()) + ". It graded correctness "
                    f"on {s['correctness_graded_when_gold_null']} rows where the rubric says n/a.", ""]
        else:
            gaps.append(f"judge on {p.parent.name} not checked against the exact abstention answer: "
                        f"run `python scripts/judge.py summarise --name {p.parent.name}`")
        agree = p.parent / "agreement.json"
        if agree.is_file():
            a = json.loads(agree.read_text(encoding="utf-8"))
            def k_(t):   # judge.cohen's (n, raw agreement, kappa); kappa is None when only one category occurs
                n, raw, kappa = t
                return f"κ {kappa} (raw {raw})" if kappa is not None else f"κ undefined, one category (raw {raw})"
            n = next(iter(a.values()))["human_vs_human"][0]
            out += [f"**Human spot-check** ({n} rows, two graders working independently): Cohen's κ, raw agreement in "
                    "brackets.", "", "| Axis | human vs human | judge vs grader 1 | judge vs grader 2 |", "|---|---|---|---|"]
            out += [f"| {k} | {k_(v['human_vs_human'])} | {k_(v['judge_vs_grader_1'])} | {k_(v['judge_vs_grader_2'])} |"
                    for k, v in a.items()]
            out.append("")
        else:
            out += [f"Human spot-check κ: {NM}.", ""]
            gaps.append(f"human spot-check of the judge on {p.parent.name}: two graders, Cohen's κ (3.7)")

    out += ["## Served latency (3.8, 3.14)", ""]
    # Only the 3.14 in-process benches: Week 4 writes other reports here (4.1 merge check, 4.3 HTTP bench).
    serve = [p for p in sorted((REPO / "results/serve").glob("*.json"))
             if json.loads(p.read_text(encoding="utf-8")).get("task") == "3.14"]
    if serve:
        out += ["Merged bf16, `transformers.generate`, batch 1, one request at a time, the same 50 val requests for "
                "every adapter. Latency is end to end minus HTTP.", "",
                "| Run | e2e p50 (s) | e2e p95 (s) | TTFT p50 (s) | decode tok/s p50 | overall tok/s | mean new tokens "
                "| accuracy on these items |", "|---|---|---|---|---|---|---|---|"]
        for p in serve:
            b = json.loads(p.read_text(encoding="utf-8"))
            m = b["summary"]
            out.append(f"| {b['run']} | {m['e2e_s']['p50']} | {m['e2e_s']['p95']} | {m['ttft_s']['p50']} | "
                       f"{m['decode_tok_s']['p50']} | {m['overall_tok_s']} | {m['mean_new_tokens']} | "
                       f"{pct(m['accuracy_on_these_items'])} |")
        out.append("")
    else:
        out += [f"Served latency: {NM}.", ""]
    for run in ("run_a_r16", "ablation_answer_only"):
        if not (REPO / f"results/serve/{run}.json").is_file():
            gaps.append(f"served latency for {run} not measured (3.8, 3.14)")
    for run in ("run_a_r16_table", "run_a_r16_vision"):
        if not list((REPO / "results/evals").glob(f"{run}-*")):
            gaps.append(f"{run} not trained or not evaluated (3.0h/3.0j)")
    gaps.append("data-quality audit kappa not reported (3.0i): needs two or three human reviewers")

    out += ["## What Week 3 has not yet established", ""] + [f"- {g}" for g in gaps]
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--write", action="store_true")
    args = ap.parse_args()
    text = build()
    print(text)
    if args.write:
        (REPO / "docs/report_draft_week3.md").write_text(text, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
