#!/usr/bin/env python3
"""Week 4 results draft (task 4.7), generated from committed artefacts: no figure in it is typed by hand.

  python scripts/report_week4.py            # print
  python scripts/report_week4.py --write    # write docs/report_draft_week4.md

Like the Week 3 draft and the model card, every section renders a number read from results/ or the string NOT
MEASURED. It closes with what the week did NOT establish, assembled from the run's own gaps (the model card's NOT
MEASURED items, the clean-clone check's warnings, and verdicts that ruled something out) rather than from memory on
the day of writing.
"""
import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "scripts"))
NM = "NOT MEASURED"
DRAFT = "docs/report_draft_week4.md"


def read(root, rel):
    p = Path(root) / rel
    return json.loads(p.read_text(encoding="utf-8")) if p.is_file() else None


def build(root=REPO):
    from serve import modelcard
    gaps, not_established = [], []
    out = ["# Week 4 results — generated draft", "",
           "_Generated by `scripts/report_week4.py` from committed files; regenerate, do not edit._", ""]

    m = read(root, "results/serve/merge_run_a_r16.json")
    out += ["## 4.1 Verified merge", ""]
    if m:
        w, a = m["weight_check"], m["answer_check"]
        out += [f"Status **{m['status']}** (job {m['slurm_job_id']}, commit `{m['git_commit'][:7]}`). Base check: "
                f"`{m['base_check']['base']}` at revision `{m['base_check']['base_revision'][:12]}`, the revision the "
                f"adapter was trained on. Weights: {w['modules_checked']} modules equal base + "
                f"{m['base_check']['scaling']:g}·B@A computed from the adapter file, {w['elements_rounded_differently']} "
                f"of {w['elements_changed_by_merge']:,} changed elements off; {w['tensors_unchanged']} other tensors "
                f"bit-identical; {w['dtype']}. Answers on {a['n']} val items: {a['disagree']} parsed answers differ "
                f"(tolerance {a['tolerance']['max_disagree']}), {a['raw_identical']} raw outputs identical, "
                f"{a['correct']['merged']} vs {a['correct']['reference']} correct.", ""]
    else:
        out += [f"Merge verification: {NM}.", ""]
        gaps.append("the verified merge (4.1)")

    q = read(root, "results/serve/quantise_run_a_r16.json")
    out += ["## 4.2 Quantisation", ""]
    if q and q.get("status") == "MEASURED":
        acc, d, ex = q["accuracy"], q["discordant"], q.get("export", {})
        out += [f"GPTQ {q['scheme']['bits']}-bit, group {q['scheme']['group_size']}, on the {q['targets']['quantise']} "
                f"decoder projections; vision tower and merger kept ({q['targets']['keep']['vision tower and merger']} "
                f"modules). Calibration: {q['calibration']['n']} train conversations, disjoint from "
                f"{len(q['calibration']['disjoint_from'])} evaluation sets. Export {ex.get('tensor_bytes', 0) / 2**30:.2f} GB.",
                "",
                f"| On {q['headline']['split']} ({q['n']} items) | bf16 | 4-bit |", "|---|---|---|",
                f"| Accuracy | {100 * acc['bf16']:.1f}% | {100 * acc['quantised']:.1f}% |",
                f"| Contract-valid | {q['contract_valid']['bf16']} | {q['contract_valid']['quantised']} |",
                f"| Mean seconds per answer | {q['mean_seconds']['bf16']} | {q['mean_seconds']['quantised']} |", "",
                f"Drop {100 * acc['drop']:.2f} points against a tolerance of {100 * q['tolerance']['max_accuracy_drop']:.1f} "
                f"fixed before measuring; {d['lost']} lost, {d['gained']} gained (McNemar p = {d['mcnemar_p']}). "
                f"**Verdict: {q['verdict']}** — the bf16 merge is served.", ""]
        if q["verdict"] == "REJECT":
            not_established.append(f"a quantised deployment: 4-bit was rejected ({100 * acc['drop']:.2f}-point drop "
                                   f"against a {100 * q['tolerance']['max_accuracy_drop']:.1f}-point tolerance), and it ran "
                                   "slower without compiled GPTQ kernels")
    elif q:
        out += [f"Status {q.get('status')}: {q.get('exception')}.", ""]
        not_established.append("a quantised deployment: the backend failed (recorded downgrade)")
    else:
        out += [f"Quantisation: {NM}.", ""]
        gaps.append("the quantisation delta (4.2)")

    h = read(root, "results/serve/run_a_r16_http.json")
    out += ["## 4.3 Endpoint", ""]
    if h:
        s, cnt = h["summary"], h["endpoint_counters_over_timed_requests"]
        v = s["vs_in_process_3_14"]
        degraded = [r["id"] for r in h["requests"] if r.get("degraded")]
        out += [f"`{h['health']['serving']['engine']}` behind FastAPI, {h['health']['serving']['precision']}, batch "
                f"{h['health']['serving']['batch_size']}. The {s['n']} requests 3.14 timed in-process, sent over HTTP:", "",
                "| | In-process (3.14) | Endpoint (4.3) |", "|---|---|---|",
                f"| p50 latency | {v['in_process_e2e_s']['p50']} s | {s['e2e_s']['p50']} s |",
                f"| p95 latency | {v['in_process_e2e_s']['p95']} s | {s['e2e_s']['p95']} s |",
                f"| Accuracy on these items | {100 * v['in_process_accuracy']:.0f}% | {100 * s['accuracy_on_these_items']:.0f}% |",
                f"| Contract-valid | {100 * v['in_process_schema_valid']:.0f}% | {100 * s['schema_valid']:.0f}% |", "",
                f"HTTP, JSON and base64 cost {s['overhead_s']['p50'] * 1000:.0f} ms at p50. Counters: "
                f"{cnt['first_attempt_valid']}/{cnt['answered']} valid first time, {cnt['retried']} retried, "
                f"{cnt['degraded']} degraded" + (f" ({', '.join(degraded)})" if degraded else "") + ".", ""]
        not_established.append("throughput under concurrent load: every latency is one request at a time "
                               "(transformers.generate, no continuous batching)")
    else:
        out += [f"Served latency over HTTP: {NM}.", ""]
        gaps.append("served latency over HTTP (4.3)")

    c = read(root, "results/serve/container_smoke.json")
    out += ["## 4.4 Container", "",
            "`docker/Dockerfile` and `compose.yaml`: installs `requirements-serve.txt` (a verbatim subset of the lock) "
            "with `--no-deps` and `pip check`; weights bind-mounted read-only; healthy only when the mounted merge "
            "manifest is VERIFIED. These rules are checked by `tests/test_container.py`.", "",
            f"Built and run on a GPU: {c.get('summary') if c else NM}.", ""]  # an unrun container is a card gap

    r = read(root, "results/redteam/run_a_r16.json")
    out += ["## 4.5 Red-team", ""]
    if r:
        s = r["summary"]
        out += [f"{s['n']} attacks on the deployed endpoint (job {r['slurm_job_id']}). Resisted **{s['resisted']}/{s['n']}**: "
                f"answer families {s['answer_families_resisted']}, abstain families {s['abstain_families_resisted']} "
                f"(always abstaining would resist {s['reference_points']['always_abstain_resists']}/21).", "",
                "| Family | " + " | ".join(o for o in ("resisted", "misled", "wrong", "wrongly_abstained", "failed_to_abstain")) + " |",
                "|---|---|---|---|---|---|"]
        for fam, cnt in s["by_family"].items():
            out.append(f"| {fam} | " + " | ".join(str(cnt.get(o, 0)) for o in
                                                  ("resisted", "misled", "wrong", "wrongly_abstained", "failed_to_abstain")) + " |")
        out += ["", f"Prompt injection obeyed {s['injection_obeyed']}/3. Failures to abstain: "
                + "; ".join(f"{a['id']} answered {a['answer']}" for a in r["attempts"] if a["outcome"] == "failed_to_abstain")
                + ". Log: `results/redteam/run_a_r16.md`.", ""]
        abst = s["abstain_families_resisted"].split("/")
        if abst[0] != abst[1]:
            not_established.append(f"reliable abstention on adversarial charts: {s['abstain_families_resisted']} abstain "
                                   "attacks resisted; the model states the information is missing and answers anyway")
    else:
        out += [f"Red-team log: {NM}.", ""]
        gaps.append("the red-team log (4.5)")

    _, card_gaps = modelcard.build(root)
    out += ["## 4.6 Model card", "", f"`MODEL_CARD.md`, generated by `scripts/serve/modelcard.py`, with "
            f"{len(card_gaps)} NOT MEASURED item(s).", ""]

    rel = read(root, "results/release/clean_clone.json")
    out += ["## 4.7 Clean-clone check", ""]
    if rel:
        out += [f"Commit `{rel['commit'][:7]}`, {rel['tracked_files']} files, cloned fresh: **{rel['verdict']}** with "
                f"{len(rel['blocking'])} blocking finding(s) and {len(rel['warnings'])} warning(s). "
                + (f"Tests in the clone: {rel['checks']['tests_summary']}. " if "tests_summary" in rel["checks"] else "")
                + f"{rel['checks'].get('manifest_files', 0)} manifest-listed data files verified by hash.", ""]
        out += [f"- {w['detail']}" for w in rel["warnings"] if w["check"] != "not_measured"] + [""]
        if rel["blocking"]:
            not_established.append(f"a reproducible clone: {len(rel['blocking'])} blocking finding(s)")
    else:
        out += [f"Clean-clone check: {NM}.", ""]
        gaps.append("the clean-clone check (4.7)")

    if not (Path(root) / "data" / "eval_b").exists():
        not_established.append("generalisation to unseen chart styles: no out-of-distribution set (Eval-B) was built")
    not_established += [g for g in card_gaps]
    out += ["## What Week 4 did not establish", "",
            "_Assembled from the gaps the results themselves declare._", ""]
    out += [f"- {x}" for x in not_established + [f"{g}: {NM}" for g in gaps]] or ["- nothing"]
    return "\n".join(out).rstrip() + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--write", action="store_true")
    args = ap.parse_args(argv)
    text = build()
    if args.write:
        (REPO / DRAFT).write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {DRAFT}")
    else:
        print(text, end="")
    return 0


if __name__ == "__main__":
    sys.exit(main())
