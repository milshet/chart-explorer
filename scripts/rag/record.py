#!/usr/bin/env python3
"""The RAG decision record (task 3.12), generated from results/rag/retrieval.json and the corpus stats.

  python scripts/rag/record.py            # print
  python scripts/rag/record.py --write    # write docs/RAG.md

Template item 5 asks for chunking, the embedding model and the reranker to each be a documented decision. Each
section below gives the candidates, the selection-set measurement, the rule (fixed before measuring, plan tasks
3.4, 3.10, 3.11) and the outcome. A candidate with no row in retrieval.json renders as NOT MEASURED; nothing here
is typed by hand, so regenerating after a VM03 run is the whole update.
"""
import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from rag import retrieve as R  # noqa: E402

REPO = Path(__file__).resolve().parents[2]
NM = "NOT MEASURED"
OUT = REPO / "docs" / "RAG.md"


def key(m):
    return (m["recall@1"], m["mrr"])


def find(results, **kw):
    return next((x for x in results if all(x[k] == v for k, v in kw.items())), None)


def cells(m, extra=()):
    return [str(m[k]) for k in ("recall@1", "recall@3", "recall@5", "mrr")] + [str(m.get(k, "")) for k in extra]


def verdict(row, floor):
    """The adoption rule is judged under chart_metadata, the plan the configuration is chosen on; question_only
    rows are the bracket's other end and say only whether they beat BM25 there."""
    if row is None:
        return NM
    wins = key(row["metrics"]) > key(floor["metrics"])
    if row["plan"] != "chart_metadata":
        return "beats BM25 on this plan (not the selection plan)" if wins else "does not beat BM25"
    return "**beats BM25: adopt**" if wins else "rejected: does not beat BM25"


def rev(info):
    return f"`{info['revision'][:10]}`" if info.get("revision") else "not recorded"


def build():
    r = json.loads((REPO / "results/rag/retrieval.json").read_text(encoding="utf-8"))
    st = json.loads((REPO / "data/v2.0/tables/table_index.json").read_text(encoding="utf-8"))["stats"]
    res, sel, ch = r["selection"]["results"], r["selection"], r["chosen"]
    plans = ("chart_metadata", "question_only")
    floor = {p: find(res, chunking="whole_table", plan=p, retriever="bm25") for p in plans}
    out = ["# RAG decision record", "",
           "_Generated by `scripts/rag/record.py` from `results/rag/retrieval.json`; regenerate, do not edit._", "",
           f"Every choice below was made on a **selection set of {sel['n']} rows drawn from `{sel['from']}`** "
           f"(seed {sel['seed']}), never on the reported split, by **recall@1, then MRR; an exact tie goes to the "
           "lexical retriever**, which has no model to serve. Corpus sha256 "
           f"`{r['corpus_sha256'][:12]}…`.", "",
           f"**Chosen configuration:** {ch['chunking']} chunks, `{ch['retriever']}` retriever, `{ch['plan']}` "
           f"query plan ({r['chosen_basis']}).", ""]

    over = st["tables"] - 1000
    out += ["## 1. Corpus size", "",
            f"{st['tables']} tables / {st['rows']} rows: every chart in the freeze, {st['from_records']} from frozen "
            f"records and {st['distractor_only']} distractor-only. That is {over} above the template's 200–1,000 band "
            f"({100 * over / 1000:.0f}%). **Decision: keep all {st['tables']}** (plan §9 decision 14). Task 3.1 allows "
            f"a trim only of distractors and only if the embedding budget forces one. It did not, and only "
            f"{st['distractor_only']} tables are distractor-only, so reaching 1,000 would drop gold tables.", ""]

    out += ["## 2. Chunking", "", "Whole-table vs row-group (every row-group chunk repeats the title, axis, series "
            "names and column headers). Lexical retrievers, both plans:", "",
            "| Chunking | Plan | Retriever | recall@1 | recall@3 | recall@5 | MRR |", "|---|---|---|---|---|---|---|"]
    for p in plans:
        for s in ("whole_table", "row_group"):
            for k in R.LEXICAL:
                x = find(res, chunking=s, plan=p, retriever=k)
                if x:
                    out.append(f"| {s} | {p} | {k} | " + " | ".join(cells(x["metrics"])) + " |")
    out += ["", f"**Outcome:** {ch['chunking']}.", ""]

    best = {p: max((x for x in res if x["plan"] == p), key=lambda x: key(x["metrics"])) for p in plans}
    gap = round(best["chart_metadata"]["metrics"]["recall@1"] - best["question_only"]["metrics"]["recall@1"], 2)
    spread = max(round(max(x["metrics"]["recall@1"] for x in res if x["plan"] == p)
                       - min(x["metrics"]["recall@1"] for x in res if x["plan"] == p), 2) for p in plans)
    out += ["## 3. Query plan", "",
            "`chart_metadata` (title, axis and legend text read off the chart the user sees) against `question_only`. "
            "Both are reported as a bracket on val and test. Best recall@1 on the selection set: "
            f"{best['chart_metadata']['metrics']['recall@1']} vs {best['question_only']['metrics']['recall@1']}, a gap "
            f"of {gap}. The widest recall@1 spread between any two configurations within one plan is {spread}"
            + (", so **the query plan matters more than every other choice in this record**." if gap > spread
               else "."), ""]

    out += ["## 4. Embedding model", "",
            "Rule (task 3.10): adopt only if it beats BM25 on recall@1, then MRR, on the selection set. Whole-table "
            "chunks; the row-group rows are in `retrieval.json`.", "",
            "| Model | Plan | recall@1 | recall@3 | recall@5 | MRR | Passages truncated | Revision | Outcome |",
            "|---|---|---|---|---|---|---|---|---|"]
    for p in plans:
        out.append(f"| BM25 (floor) | {p} | " + " | ".join(cells(floor[p]["metrics"])) + " | – | – | floor |")
        for name, spec in R.EMBED_MODELS.items():
            x = find(res, chunking="whole_table", plan=p, retriever=f"embed:{name}")
            if x is None and name == "minilm":   # measured before task 3.10 named the models
                x = find(res, chunking="whole_table", plan=p, retriever="embed")
            if x is None:
                out.append(f"| `{spec['id']}` | {p} | {NM} | | | | | | {NM} |")
                continue
            info = x.get("model", {})
            trunc = f"{info['passages_truncated']}/{info['passages']}" if "passages" in info else "not recorded"
            out.append(f"| `{spec['id']}` | {p} | " + " | ".join(cells(x["metrics"])) +
                       f" | {trunc} | {rev(info)} | {verdict(x, floor[p])} |")
    out.append("")

    out += ["## 5. Reranker", "",
            "A cross-encoder reorders BM25's top tables. It can only reorder what BM25 hands it, so each row carries "
            "BM25's recall at that depth as its **ceiling**. Rule (task 3.11): adopt only if it beats BM25 on "
            "recall@1, then MRR, on the selection set.", "",
            "| Reranker | Plan | Depth | Ceiling | recall@1 | recall@3 | recall@5 | MRR | Pairs truncated | Outcome |",
            "|---|---|---|---|---|---|---|---|---|---|"]
    for p in plans:
        for name, spec in R.RERANKERS.items():
            x = find(res, chunking="whole_table", plan=p, retriever=f"bm25>rerank:{name}")
            if x is None:
                out.append(f"| `{spec['id']}` | {p} | {R.RERANK_DEPTH[p]} | {NM} | | | | | | {NM} |")
                continue
            m, info = x["metrics"], x["model"]
            ceil = m[f"ceiling_recall@{info['depth']}"]
            out.append(f"| `{spec['id']}` | {p} | {info['depth']} | {ceil} | " + " | ".join(cells(m)) +
                       f" | {info['pairs_truncated']}/{info['pairs']} | {verdict(x, floor[p])} |")
    out += ["", "`cross-encoder/ms-marco-MiniLM-L-6-v2` is trained on MS MARCO, whose licence is non-commercial "
            "research only; the model card says so.", ""]

    adopted = ch["retriever"] not in R.LEXICAL
    out += ["## 6. What the outcome costs", "",
            ("A model-backed retriever was adopted, so `data/rag/` must be rebuilt with `scripts/rag/prompts.py "
             "--write` and the task 3.5/3.6 RAG evaluations rerun before any RAG number is quoted."
             if adopted else
             "Nothing model-backed was adopted, so the RAG prompt sets and every task 3.5/3.6 number stand as "
             "committed. Serving needs no embedding or reranking model."), "",
            "## 7. Headline retrieval (chosen configuration, both plans)", "",
            "| Split / plan | recall@1 | recall@3 | recall@5 | MRR | n scorable | n unscorable |",
            "|---|---|---|---|---|---|---|"]
    for k, m in r["headline"].items():
        out.append(f"| {k} | " + " | ".join(cells(m)) + f" | {m['n_scorable']} | {m['n_unscorable']} |")
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--write", action="store_true")
    args = ap.parse_args()
    text = build()
    print(text)
    if args.write:
        OUT.write_text(text, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
