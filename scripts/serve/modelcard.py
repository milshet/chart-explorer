#!/usr/bin/env python3
"""Task 4.6: the model card, generated from committed results. No number in it is typed by hand.

  python scripts/serve/modelcard.py            # print
  python scripts/serve/modelcard.py --write    # write MODEL_CARD.md
  python scripts/serve/modelcard.py --check    # exit 1 if MODEL_CARD.md is stale (tests run this)

A card is a document full of numbers, and numbers retyped by hand drift from the runs that produced them. So every
figure here is read from results/, data/ or blind_labelling/ at build time, and one rule shapes every section: a
number that was not measured says so. Each section renders a figure or the string NOT MEASURED, never nothing,
because an omitted row reads as "no issue here", and a reader cannot otherwise tell a model that abstains well from
one whose abstention nobody checked. Every NOT MEASURED is also collected into the closing list of gaps, which is
how the end-of-week gate counts them.

Comparisons between models are paired exact McNemar tests on identical items, computed here from the committed
predictions, never differences of two percentages.
"""
