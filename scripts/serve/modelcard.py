def evaluation(c):
    c.add("## Evaluation", "")
    t = summary(c, f"{SERVED}_test_image_only_cot_0shot_bf16")
    if not t:
        c.add(f"Test accuracy: {c.nm('Run A on the test split')}.", "")
        return
    c.add(f"Test split (Eval-A), {t['n']} human-answered items never used for training or model selection. Relaxed "
          f"accuracy (numbers within 5%, text normalised) **{pct(t['relaxed_accuracy'])}**; JSON-valid "
          f"{pct(t['json_valid'])}, schema-valid {pct(t['schema_valid'])}; {pct(t['evidence_grounded'])} of the numbers "
          "it cites as evidence appear in the chart's data table.", "")
    s = c.read(f"{EVALS}/{SERVED}_test_image_only_cot_0shot_bf16/summary.json")
    c.add("| Question type | Accuracy | n |", "|---|---|---|",
          *[f"| {k} | {pct(v['mean'])} | {v['count']} |" for k, v in s["by"]["question_type"].items()], "")
    rows = ["| Compared with | Its accuracy | Run A | Discordant (Run A only / it only) | McNemar p |", "|---|---|---|---|---|"]
    for label, other in (("base model, 2-shot", "base_test_image_only_answer_only_2shot_4bit"),
                         ("answer-only ablation (no evidence/rationale)", "ablation_answer_only-adapter_test_image_only_answer_only_0shot_bf16"),
                         ("rank 64 (Run B)", "run_b_r64-adapter_test_image_only_cot_0shot_bf16"),
                         ("vision tower also adapted (3.0j)", "run_a_r16_vision-adapter_test_image_only_cot_0shot_bf16")):
        p = paired(c, f"{SERVED}_test_image_only_cot_0shot_bf16", other)
