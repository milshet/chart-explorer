    if j and j.get("abstention_vs_exact"):
        x = j["abstention_vs_exact"]
        c.add(f"- **LLM judge (3.7)** (`{j['judge_model']}`): its abstention verdict matches the exact answer on "
              f"{frac(x['agree'], x['n'])} rows.")
