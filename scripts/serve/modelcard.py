def limitations(c):
    c.add("## Limitations", "",
          "- **No out-of-distribution test.** No chart generator was built for an unseen-style evaluation set (Eval-B), "
          "so nothing here shows the model generalises beyond ChartQA's chart styles.",
          "- **Small test set.** One accuracy on 180 items carries roughly ±7 points; claims rest on paired tests, "
          "and differences of a few points are not established.",
          "- **English, finance and economics only,** from four publishers' chart styles.", "")
    c.add("## Not measured", "")
    if c.gaps:
        c.add(f"{len(c.gaps)} item(s) in this card are NOT MEASURED:", "", *[f"- {g}" for g in c.gaps])
    else:
        c.add("Every section of this card is measured.")
    c.add("")


def build(root=REPO):
    c = Card(root)
    for section in (header, intended_use, provenance, licences, evaluation, failure_modes, refusals, deployment,
                    limitations):
        section(c)
    return "\n".join(c.lines).rstrip() + "\n", c.gaps


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true", help="exit 1 if the committed card differs from a fresh build")
    args = ap.parse_args(argv)
    text, gaps = build()
    path = REPO / CARD
    if args.check:
        same = path.is_file() and path.read_text(encoding="utf-8") == text
        print("MODEL_CARD.md is current" if same else "MODEL_CARD.md is stale: run scripts/serve/modelcard.py --write")
        return 0 if same else 1
    if args.write:
        path.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {CARD}: {len(gaps)} NOT MEASURED")
    else:
        print(text)
    return 0


