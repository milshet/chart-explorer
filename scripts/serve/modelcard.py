class Card:
    """Lines plus the gaps they declare: `nm(reason)` renders NOT MEASURED and records why."""

    def __init__(self, root):
        self.root, self.lines, self.gaps = Path(root), [], []

    def read(self, rel):
        p = self.root / rel
        if not p.is_file():
            return None
        return json.loads(p.read_text(encoding="utf-8")) if p.suffix == ".json" else p.read_text(encoding="utf-8")

    def jsonl(self, rel):
        p = self.root / rel
        return [json.loads(l) for l in p.read_text(encoding="utf-8").splitlines() if l.strip()] if p.is_file() else None

    def nm(self, what):
        self.gaps.append(what)
        return NM

    def add(self, *lines):
        self.lines.extend(lines)


def pct(v, digits=1):
    return f"{100 * v:.{digits}f}%"


def frac(k, n):
    return f"{k}/{n} ({pct(k / n)})" if n else "0/0"


def summary(c, name):
    s = c.read(f"{EVALS}/{name}/summary.json")
    return s["overall"] if s else None


def paired(c, a, b):
    """(a correct, b correct, n, a-only, b-only, McNemar p) on the items both evaluations scored."""
    pa, pb = c.jsonl(f"{EVALS}/{a}/predictions.jsonl"), c.jsonl(f"{EVALS}/{b}/predictions.jsonl")
    if not pa or not pb:
        return None
    ra, rb = {r["id"]: r["correct"] for r in pa}, {r["id"]: r["correct"] for r in pb}
    ids = sorted(set(ra) & set(rb))
    only_a = sum(ra[i] and not rb[i] for i in ids)
    only_b = sum(rb[i] and not ra[i] for i in ids)
    return (sum(ra[i] for i in ids), sum(rb[i] for i in ids), len(ids), only_a, only_b, mcnemar_exact(only_a, only_b))


def matches(c, run):
    rows = c.jsonl(f"blind_labelling/runs/{run}/compare.jsonl")
    return (sum(r["match"] == "exact" for r in rows), len(rows)) if rows else None


